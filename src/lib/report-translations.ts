export function translateReportText(text: string, isTelugu: boolean): string {
  if (!isTelugu) return text;
  if (telugu[text]) return telugu[text];
  const symptoms = text.match(/^(\d+) symptoms? reported$/);
  if (symptoms) return `${symptoms[1]} లక్షణాలు నివేదించబడ్డాయి`;
  if (text.endsWith(" clinical report")) {
    return `${translateReportText(text.replace(/ clinical report$/, ""), true)} — వైద్య నివేదిక`;
  }
  const parts = text.split(/( — |: | · )/);
  if (parts.length > 1) return parts.map((part) => translateReportText(part, true)).join("");
  const units = text.match(/^(.*) units this week$/);
  if (units) return `ఈ వారంలో ${units[1]} యూనిట్లు`;
  return text;
}

export function useReportText() {
  const { language } = usePulse();
  return (text: string) => translateReportText(text, language === "te");
}
